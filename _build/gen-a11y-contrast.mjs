/** Generate next-app/app/a11y-contrast.css from the latest Lighthouse sweep,
 *  keyed on STABLE class names (selector paths vary run to run).
 *  Only two families need class overrides — everything else is fixed at
 *  source (tokens, footer, CTA sections):
 *   - golden (champagne) text on a light surface -> var(--sky-text)
 *   - light text on a champagne surface          -> var(--ink)
 *  Accumulates in a11y-classmap.json across runs; skips dark-surface items
 *  (those are token-level and already handled in source).
 */
import fs from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MAP_FILE = join(HERE, 'a11y-classmap.json');
const rows = JSON.parse(fs.readFileSync(join(HERE, 'a11y-sweep.json'), 'utf8'));
const map = fs.existsSync(MAP_FILE) ? JSON.parse(fs.readFileSync(MAP_FILE, 'utf8')) : {};

const lum = (hex) => {
  const c = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(c.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const isGolden = (hex) => {
  const c = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(c.slice(i, i + 2), 16));
  return r > g && g > b && r - b > 40;
};

let used = 0, skipped = 0;
for (const r of rows) {
  if (r.audit !== 'color-contrast') continue;
  if (/swf-|btn--wa|btn--whatsapp/.test(r.sel + r.snip)) continue;
  const cm = r.snip.match(/class="([a-z0-9_-]+)/i);
  if (!cm) { skipped++; continue; }
  const cls = cm[1];
  const m = r.expl.match(/foreground color: (#[0-9a-f]{6}).*?background color: (#[0-9a-f]{6})/i);
  if (!m) { skipped++; continue; }
  const [, fg, bg] = m;
  const bgL = lum(bg);
  // buttons, h2s and finalcta content are fixed at source; skip dual-risk classes
  if (/btn|-h2$|finalcta/.test(cls)) { skipped++; continue; }
  if (bgL >= 0.3 && isGolden(bg)) { map['.' + cls] = 'var(--ink)'; used++; } // anything on champagne -> ink
  else if (bgL >= 0.35 && isGolden(fg)) { map['.' + cls] = 'var(--sky-text)'; used++; }
  else if (bgL >= 0.35 && lum(fg) > 0.25) { map['.' + cls] = 'rgba(12,14,19,0.65)'; used++; } // dim text on light
  else skipped++; // dark-surface items handled at source token level
}

fs.writeFileSync(MAP_FILE, JSON.stringify(map, null, 1));
let css = '/* GENERATED by _build/gen-a11y-contrast.mjs — class-level contrast fixes\n   for champagne text on light surfaces. Regenerate, do not hand-edit. */\n';
const byColor = {};
for (const [sel, color] of Object.entries(map)) (byColor[color] = byColor[color] || []).push(sel);
// `html .cls` outranks the page stylesheets' plain `.cls` rules regardless of
// import order (0,1,1 vs 0,1,0)
for (const [color, sels] of Object.entries(byColor)) css += sels.map((x) => 'html body ' + x).join(', ') + ` { color: ${color}; }\n`;
// eyebrow classes are dual-context: restore bright champagne inside dark heroes
const eyebrows = Object.keys(map).filter((c) => c.endsWith('-eyebrow') || c === '.sw-eyebrow');
if (eyebrows.length) {
  css += eyebrows.map((e) => `html body [class*='hero'] ${e}, html body [class*='--dark'] ${e}, html body [class*='--ink'] ${e}`).join(',\n') + ' { color: var(--sky); }\n';
}
fs.writeFileSync(join(HERE, '..', 'next-app', 'app', 'a11y-contrast.css'), css);
console.log(`class overrides: ${Object.keys(map).length} (${used} confirmed this run, ${skipped} handled at source)`);
